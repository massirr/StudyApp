// Unit-pixel coordinates (x,y) for each lit pixel across the whole label.
export function glyphRectsFor(text: string): { x: number; y: number }[] {
  if (!isSupportedLabel(text)) {
    throw new Error(`pixelFont: unsupported text "${text}"`);
  }
  const rects: { x: number; y: number }[] = [];
  let cursorX = 0;
  for (const ch of text) {
    if (ch === ' ') {
      cursorX += GLYPH_W + GAP;
      continue;
    }
    const rows = GLYPHS[ch];
    if (!rows) throw new Error(`pixelFont: no glyph for "${ch}"`);
    rows.forEach((row, y) => {
      [...row].forEach((bit, x) => {
        if (bit === '1') rects.push({ x: cursorX + x, y });
      });
    });
    cursorX += GLYPH_W + GAP;
  }
  return rects;
}

export function labelWidth(text: string): number {
  return text.length * (GLYPH_W + GAP) - GAP;
}
